"""Bundle repository-owned page objects into one deployable Python file."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
modules = {name:(ROOT / 'deploy/ui-runner' / (name + '.py')).read_text(encoding='utf-8')
    for name in ['network_evidence', 'studio_flows']}
runtime = (ROOT / 'deploy/activity-service/runtime.py').read_text(encoding='utf-8')
digest = hashlib.sha256((''.join(modules.values()) + runtime).encode()).hexdigest()
header = '# Generated by scripts/build_emote_activity.py; edit the source modules, then rebuild.\n'
header += 'BUNDLED_SOURCE_SHA256 = ' + repr(digest) + '\nimport sys, types\n'
for name, source in modules.items():
    header += f'_module = types.ModuleType({name!r})\nsys.modules[{name!r}] = _module\n'
    header += f'exec(compile({source!r}, {name!r}, "exec"), _module.__dict__)\n'
target = ROOT / 'deliverables/emote_activity_service.py'
target.parent.mkdir(exist_ok=True)
target.write_text(header + '\n' + runtime, encoding='utf-8')
print(json.dumps({'file':str(target), 'source_sha256':digest}))
