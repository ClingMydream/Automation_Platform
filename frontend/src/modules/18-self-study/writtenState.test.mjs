import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { updateWrittenAnswer, manualScore, applyAssessment, answerRevealed } from './writtenState.js';
import { validateSession } from './sessionState.js';
import { gradePaper } from './examEngine.js';
const bank={version:1,questions:[{id:'short',type:'short'},{id:'material',type:'material'}]};
const q=bank.questions[0];
let s={attemptId:'one',version:1,ids:['short','material'],index:0,responses:{},finished:false};
s=updateWrittenAnswer(s,'short','我的第一份答案');
assert.equal(gradePaper(bank.questions,s.responses,s.selfScores).pending,2);
const ticket={attemptId:'one',answer:s.writtenAnswers.short,revision:s.scoreRevisions.short};
const result={question_id:'short',max_score:7,score:5,feedback:'覆盖主要要点',strengths:['主要观点'],missing_points:['举例']};
s=applyAssessment(s,ticket,result,q);
assert.equal(gradePaper(bank.questions,s.responses,s.selfScores).total,5);
assert.equal(s.scoreSources.short,'ai');
s=manualScore(s,q,0);
assert.equal(s.selfScores.short,0);assert.equal(s.scoreSources.short,'manual');assert.equal(s.aiAssessments.short.score,5);
assert.equal(applyAssessment(s,ticket,result,q),s,'late AI must not overwrite manual score');
s=updateWrittenAnswer(s,'short','补充后的答案');
assert.equal(s.selfScores.short,undefined);assert.equal(s.aiAssessments.short,undefined);
assert.equal(applyAssessment(s,ticket,result,q),s,'stale answer must not be graded');
const fresh={...ticket,answer:s.writtenAnswers.short,revision:s.scoreRevisions.short};
assert.throws(()=>applyAssessment(s,fresh,{...result,score:8},q));
assert.equal(applyAssessment({...s,attemptId:'new-paper'},fresh,result,q).selfScores.short,undefined);
assert.equal(applyAssessment({...s,finished:true},fresh,result,q).selfScores.short,undefined);
s=manualScore(s,q,7);
s=updateWrittenAnswer(s,'material','结合材料逐条作答');s=manualScore(s,bank.questions[1],15);
assert.equal(gradePaper(bank.questions,s.responses,s.selfScores).total,22);
assert.equal(validateSession(JSON.parse(JSON.stringify(s)),bank)?.selfScores.material,15);
assert.equal(validateSession({...s,writtenAnswers:{short:22}},bank),null);
assert.equal(validateSession({...s,aiAssessments:{short:{...result,score:100}}},bank),null);
const legacy={version:1,ids:['short'],index:0,responses:{short:'viewed'},selfScores:{short:7}};
assert.equal(validateSession(legacy,bank),legacy);assert.equal(answerRevealed(legacy,'short'),true);
assert.equal(answerRevealed({...legacy,revealed:{short:false}},'short'),false);
assert.equal(gradePaper([q],legacy.responses,legacy.selfScores).total,7);
const finished={...s,finished:true};assert.equal(updateWrittenAnswer(finished,'short','改动'),finished);
assert.equal(manualScore(finished,q,1),finished);
const authoritative=JSON.parse(readFileSync(new URL('../../../../backend/app/modules/self_study/questionBank.json',import.meta.url)));
const frontend=JSON.parse(readFileSync(new URL('./questionBank.json',import.meta.url)));
assert.deepEqual(authoritative,frontend,'backend and frontend question banks must stay in sync');
console.log('PASS: AI/manual precedence, editing invalidation, late responses, zero/material scores, legacy migration and trusted bank parity.');
